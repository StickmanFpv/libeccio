"""fork: Libeccio's level matching. Reads the loudness of every factory sound (measure: tools/measure_levels.py,
the 90th percentile of the momentary loudness, LUFS, of the louder of a played line and a held chord; the kits: a beat)
and writes firmware/src/level_trim.h: a gain per engine and factory sound that brings it to the target loudness.

  tools/measure_levels.py build/host/hostsim before   (the untrimmed host build: LIBECCIO_MELODEE_DEFAULTS)
  cp build/levels/before.json tools/levels_measured.json; cp build/levels/before_peak.json tools/levels_measured_peak.json
  tools/gen_level_trim.py tools/levels_measured.json > firmware/src/level_trim.h
"""
import json, math, statistics, sys

ENG = {'SID': 3, 'DRUM': 10, 'FM6': 12, 'CZ': 15, 'PROPHET': 19, 'SEM': 22, 'HADES': 23, 'MOOG': 24, 'PULSAR': 25, 'VOICE': 26}
DRUMS = {'DRUM', 'PULSAR'}
KIT_LIFT = 2.0                                   # dB: the kits a little above the synths
MAX_CUT, MAX_BOOST = 12.0, 12.0                   # dB

PEAK_ROOM = -9.0                                 # dBFS: a trimmed sound's peak at the measure's master volume (half the
                                                 # device's: 6 dB more there), so a boost never clips

def main(path):
    lv = json.load(open(path))
    pk = json.load(open(path.replace('.json', '_peak.json')))
    # the target: where Melodee's own Prophet and CZ-1 sit (the median of their sounds)
    TARGET_SYNTH = round(statistics.median([v for nm in ('PROPHET', 'CZ') for v in lv[nm].values()]), 1)
    TARGET_DRUM = TARGET_SYNTH + KIT_LIFT
    out = ['/* SPDX-License-Identifier: GPL-3.0-only */',
           '/* fork: generated by tools/gen_level_trim.py from the measured loudness of every factory sound: do not edit.',
           ' * Each engine\'s factory sounds trimmed to one loudness (synths %.1f, kits %.1f LUFS momentary, 90th percentile, at' % (TARGET_SYNTH, TARGET_DRUM),
           ' * the measure\'s master volume: the Prophet\'s and the CZ-1\'s median),',
           ' * at most %.0f dB down, %.0f up; a user sound gets its engine\'s median. Q12 gains (4096 = 0 dB). */' % (MAX_CUT, MAX_BOOST)]
    tables = []
    for nm, e in ENG.items():
        d = lv[nm]
        vals = [d[str(p)] for p in range(len(d))]
        target = TARGET_DRUM if nm in DRUMS else TARGET_SYNTH
        peaks = [pk[nm][str(p)] for p in range(len(d))]
        db = [max(-MAX_CUT, min(MAX_BOOST, target - v, PEAK_ROOM - k)) for v, k in zip(vals, peaks)]
        med = max(-MAX_CUT, min(MAX_BOOST, target - statistics.median(vals)))
        q = [round(4096 * 10 ** (x / 20)) for x in db] + [round(4096 * 10 ** (med / 20))]
        out.append('static const uint16_t LVT_%s[%d] = {%s};   /* the last: a user sound */' % (nm, len(q), ', '.join(map(str, q))))
        tables.append((e, nm, len(vals)))
    out.append('/* engine e\'s trim for factory sound p (p >= its count, or a user sound: the median) */')
    out.append('static inline __attribute__((always_inline)) uint16_t level_trim_of(uint32_t e, uint32_t p, int user)')
    out.append('{')
    out.append('    switch (e) {')
    for e, nm, n in tables:
        out.append('    case %du: return LVT_%s[user || p >= %du ? %du : p];' % (e, nm, n, n))
    out.append('    default: return 4096u;')
    out.append('    }')
    out.append('}')
    print('\n'.join(out))

if __name__ == '__main__':
    main(sys.argv[1])
